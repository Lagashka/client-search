# -*- coding: utf-8 -*-
"""Фильтр «пишет человек, а не бот» — последний шаг перед отправкой любого первого письма и дожима (все три бота).

looks_bot(text) → причина (строка) или "" — по ней ИИ-текст отбраковывается и берётся шаблон.
humanize(text)  → мягкая чистка того, что выдаёт робота: длинные тире, «!», «Приветствую», кавычки-цитаты длинных названий,
                  точки в конце абзацев, лишние пробелы; не больше 3 сообщений.
Принципы (как пишет Егор с телефона): коротко, на запятых, со строчной после приветствия, одна конкретная деталь,
один вопрос, без перечислений услуг списком, без шаблонных «с удовольствием возьмусь», «портфолио:», без ссылок
незнакомым (кроме отклика на вакансию, где работы просят сами).
"""
import re

BOT_PHRASES = re.compile(
    r"с удовольствием возьм|готов взяться|это как раз мой профиль|задача мне подходит|моя основная специализация|"
    r"специализируюсь на|портфолио\s*:|мои работы\s*:|примеры работ\s*:|как я монтирую\s*—|работаю официально|"
    r"предложение о сотрудничеств|рад сотрудничеств|буду рад|с уважением|уважаем|обращайтесь|наша команда|"
    r"мы предлагаем|предлагаем вам|хотел бы предложить|позвольте|разрешите представиться|данн(ый|ого|ом) (канал|вакансии)|"
    r"в рамках|осуществля|является|вашего бизнеса|ваш бизнес на новый уровень|выведу|приветствую|привет\b|"
    r"надеюсь, у вас всё хорошо|надеюсь, это сообщение|не просто [^,.]{0,30}, а|важно отметить|стоит отметить|"
    r"лид(ы|ов)? для вас|увеличить продажи|охваты вырастут|гарантир", re.I)
LIST4 = re.compile(r"(?<![А-ЯЁа-яё])(?!здравствуйте|смотрите|уточню|кстати)([а-яё-]{3,},\s*){3,}[а-яё-]{3,}\b")   # 4+ слов через запятую (строчные)
PAREN_LIST = re.compile(r"\([^)]*,[^)]*,[^)]*\)")                            # (стратегия, сценарии, монтаж)
LONG_QUOTE = re.compile(r"«([^»]{40,})»")                                    # цитата длинного названия/вакансии

def parts(t):
    return [p.strip() for p in re.split(r"\n\s*\n", t or "") if p.strip()]

def looks_bot(t, allow_link=False):
    t = t or ""
    if "!" in t: return "восклицательный знак"
    if "—" in t or " – " in t: return "длинное тире"
    if re.search(r"[\U0001F300-\U0001FAFF☀-➿]", t): return "эмодзи"
    if not allow_link and re.search(r"https?://|t\.me/|www\.", t): return "ссылка незнакомому"
    m = BOT_PHRASES.search(t)
    if m: return "шаблонная фраза: " + m.group(0)
    if PAREN_LIST.search(t): return "перечисление в скобках"
    if LIST4.search(t): return "список услуг через запятую"
    if LONG_QUOTE.search(t): return "цитата названия в кавычках"
    if re.search(r"^\s*[-•*]\s", t, re.M) or ";" in t: return "списки/точка с запятой"
    ps = parts(t)
    if len(ps) > 3: return "больше 3 сообщений"
    if any(len(p) > 380 for p in ps): return "слишком длинный абзац"
    if len(t) > 750: return "слишком длинно"
    if re.search(r"(?<=[а-яё,] )(Вы|Ваш\w*)\b", t): return "«Вы» с большой"
    return ""

def humanize(t, allow_link=False):
    t = (t or "").strip()
    t = re.sub(r"\s+[—–]\s+", ", ", t).replace("—", ", ").replace("–", "-")
    t = t.replace("!", ".")
    t = re.sub(r"(?i)\bприветствую\b", "Здравствуйте", t)
    t = LONG_QUOTE.sub("", t)                                               # «Ищем монтажёра для …» — человек так не цитирует
    t = PAREN_LIST.sub("", t)
    t = re.sub(r"\s+,", ",", t); t = re.sub(r",\s*,", ",", t); t = re.sub(r",\s*\n", "\n", t)
    t = re.sub(r"[ \t]{2,}", " ", t)
    t = re.sub(r"[.…]+(?=[ \t]*(\n|$))", "", t)                             # без точки в конце абзаца, как пишет Егор
    ps = parts(t)
    if len(ps) > 3: ps = ps[:2] + [" ".join(ps[2:])]
    return "\n\n".join(p.strip(" ,") for p in ps)
