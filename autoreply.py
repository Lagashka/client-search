NICHE_IDX = {0, 1, 2, 3, 4, 8}     # подкаст, тревел, врачи, недвижимость, промо, эксперты (остальное — формат)
BOILER = re.compile(r"вакансия взята из нашего бота.*?предварительная оценка вакансии:\s*\S+\s*\S+", re.I | re.S)

def pain_for(sp, low, bio=""):
    """sp — генератор вариантов из autoclient (для уникальности). Возвращает (проблема, решение) или None.
    Ниша выбирается по весу: заголовок вакансии ×3, био ×2, остальной текст ×1."""
    low = BOILER.sub("", low.lower()).strip(); bio = (bio or "").lower()
    head, rest = low[:250], low[250:]
    best, score = None, 0
    for k, (rx, pains, sols) in enumerate(PAINS):
        s = 3 * bool(re.search(rx, head)) + bool(re.search(rx, rest)) + 2 * bool(re.search(rx, bio))
        s *= 2 if k in NICHE_IDX else 1          # ниша клиента важнее формата ролика
        if s > score: best, score = k, s
    if best is None: return None
    _, pains, sols = PAINS[best]
    return sp(*pains), sp(*sols)

