def cold_message(ch, display, niche, variant):
    """Холодное письмо эксперту: ИИ изучает канал (посты, охваты, доля видео) и пишет лично ему. None → шаблон."""
    if not llm_on(): return None
    posts = [p for p in ch.get("posts", []) if p][-6:]
    n = max(ch.get("n_posts", 1), 1)
    stats = []
    if ch.get("subs"): stats.append(f"подписчиков: {ch['subs']}")
    if ch.get("avg_views"): stats.append(f"средние просмотры поста: {ch['avg_views']}")
    stats.append(f"доля постов с видео: {int(100 * ch.get('videos', 0) / n)}%")
    dossier = (f"Эксперт: {display}\nКанал: {ch.get('title', '')}\nОписание: {(ch.get('desc') or '')[:400]}\nНиша: {niche}\n"
               + "; ".join(stats) + " (других цифр нет — не придумывай и не упоминай)\nПоследние посты:\n"
               + "\n".join("- " + re.sub(r"\s+", " ", p)[:300] for p in posts) + f"\n\nВариант CTA: {variant}")
    j, _ = _llm(COLD, [{"role": "user", "content": dossier}])
    if not j: return None
    txt = str(j.get("text", "")).strip()
    if len(txt) < 200 or len(txt) > 1500 or "zakulisy715" not in txt or not _sane(txt): return None
    if re.search(r"просмотр\w*\s*[—:-]?\s*0(?!\d)|\b0 подписчик|я снимаю|досье|здравствуйте,? (эксперт|команда|ипотечный|ан\b)|\d+.секундн", txt, re.I): return None   # выдумки/канцелярит
    if not re.search(r"Я Егор|Меня зовут Егор|Егор, монтаж", txt): return None                    # представиться обязательно
    return txt

