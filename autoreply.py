_FREE_LAST = [0.0]     # когда последний раз дёргали бесплатный ИИ
_DEAD = set()          # провайдеры с негодным ключом/моделью — до перезапуска не дёргаем
_COOL = {}             # провайдер → время, до которого пауза из-за лимита (429)
LAST_ERR = {}          # последняя ошибка по провайдеру — для лога

def _alive(name):
    return name not in _DEAD and _COOL.get(name, 0) < time.time()

def llm_on():
    return any(_alive(p[0]) for p in _providers())

def _call(name, url, key, model, system, messages, max_tokens):
    if name == "free": key = ""
    if name == "anthropic":
        body = {"model": model, "max_tokens": max_tokens, "system": system, "messages": messages}
        hdr = {"content-type": "application/json", "x-api-key": key, "anthropic-version": "2023-06-01"}
    else:
        body = {"model": model, "max_tokens": max_tokens, "temperature": 0.7,
                "messages": [{"role": "system", "content": system}] + messages}
        hdr = {"content-type": "application/json"}
        if key: hdr["authorization"] = f"Bearer {key}"
    hdr["User-Agent"] = "client-search/1.0"          # без него Groq/Cloudflare отвечает 403
    r = json.loads(urllib.request.urlopen(urllib.request.Request(url, data=json.dumps(body).encode(), headers=hdr), timeout=60).read())
    out = r["content"][0]["text"] if name == "anthropic" else r["choices"][0]["message"]["content"]
    out = re.sub(r"<think>.*?</think>", "", out or "", flags=re.S)          # модели с «размышлениями»
    m = re.search(r"\{.*\}", out, re.S)
    if not m: raise ValueError("ответ без JSON")
    return json.loads(m.group(0))

def _llm(system, messages, max_tokens=700):
    for name, url, key, model in _providers():
        if not _alive(name): continue
        for attempt in range(4 if name == "free" else 2):
            if name == "free":                                                 # бесплатный: 1 запрос в 45 с с одного IP — ждём свою очередь
                wait = _FREE_LAST[0] + 46 - time.time()
                if wait > 0: time.sleep(min(wait, 50))
            try:
                try: return _call(name, url, key, model, system, messages, max_tokens), name
                finally:
                    if name == "free": _FREE_LAST[0] = time.time()
            except urllib.error.HTTPError as e:
                body = e.read()[:300]
                LAST_ERR[name] = f"HTTP {e.code}: {body!r}"
                if name == "free" and (e.code in (402, 429) and b"FREE_LIMIT" in body or e.code == 429):
                    m = re.search(rb"[Rr]etry after (\d+)", body)
                    time.sleep(min(int(m.group(1)) + 2 if m else 20, 50)); continue
                if e.code in (401, 402, 403, 404): _DEAD.add(name); break     # ключ/модель не годятся — до перезапуска
                if e.code == 429:                                              # лимит в минуту: ждём и пробуем ещё раз
                    wait = min(float(e.headers.get("retry-after") or 20), 30)
                    if attempt == 0: time.sleep(wait); continue
                    _COOL[name] = time.time() + 120
                break
            except Exception as e:
                LAST_ERR[name] = str(e)[:200]; break
    return None, None

def _sane(txt, ctx=""):
    """Страховка от выдумок ИИ: цена ниже прайса, «привет», прощания. ctx — слова клиента: его цифры (напр. «1500») можно повторить."""
    theirs = {re.sub(r"\D", "", x) for x in re.findall(r"\d[\d\s ]{0,6}", ctx)}
    for a in re.findall(r"(\d[\d\s ]{0,6})\s*₽", txt):
        v = re.sub(r"\D", "", a) or "0"
        if int(v) < 3000 and v not in theirs: return False
    if re.search(r"(?<![\d–-])[2-9]\s?[–-]\s?[3-9]\s*(дня|дней|суток)", txt): return False        # сроки только из фактов: 1–2 дня / 24 ч
    if "Долги без паники" in txt or "стиль-шаблон под вас" in txt and "прошлый монтажёр пропал" in txt: return False   # слепое копирование примера из промпта
    return not re.search(r"(^|\s)привет\b|хорошего дня|удачного дня|удачный день|\*\*|json", txt, re.I)

def _bio(username):
    try:
        h = urllib.request.urlopen(urllib.request.Request(f"https://t.me/{username}", headers={"User-Agent": "Mozilla/5.0"}),
                                   timeout=15).read().decode("utf-8", "replace")
        m = re.search(r'tgme_page_description[^>]*>(.*?)</div>', h, re.S)
        return re.sub(r"<[^>]+>", " ", m.group(1)).strip()[:400] if m else ""
    except Exception: return ""

