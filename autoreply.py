def pain_for(sp, low, bio=""):
    """sp — генератор вариантов из autoclient (для уникальности). Возвращает (проблема, решение) или None.
    Ниша выбирается по весу: заголовок вакансии ×3, био ×2, остальной текст ×1."""
    low = BOILER.sub("", low.lower()).strip(); bio = (bio or "").lower()
